#!/usr/bin/env node
/**
 * Build the deployable static bundle into dist/.
 * There is exactly ONE source of truth: data/*.json. This script only copies
 * those files next to the site, so JSON updates never require HTML edits.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = path.join(ROOT, 'site');
const DATA = path.join(ROOT, 'data');
const DIST = path.join(ROOT, 'dist');

fs.rmSync(DIST, { recursive: true, force: true });
fs.cpSync(SITE, DIST, { recursive: true });
fs.mkdirSync(path.join(DIST, 'data'), { recursive: true });

const jsonFiles = fs.readdirSync(DATA).filter((f) => f.endsWith('.json')).sort();
for (const f of jsonFiles) {
  fs.copyFileSync(path.join(DATA, f), path.join(DIST, 'data', f));
}
const manifest = {
  built_from: 'site/ + data/*.json',
  data_files: jsonFiles,
  note: 'Generated by scripts/build-site.mjs. Do not edit dist/ by hand.',
};
fs.writeFileSync(path.join(DIST, 'build-manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');

function count(dir) {
  let n = 0;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    n += e.isDirectory() ? count(path.join(dir, e.name)) : 1;
  }
  return n;
}
console.log(`Built dist/: ${count(DIST)} files, data: ${jsonFiles.join(', ')}`);
